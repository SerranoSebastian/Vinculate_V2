 registros_guardados integer, duplicados_actualizados integer, total_final integer,
 creado_en timestamptz not null default now(),
 hash_evento text generated always as (md5(coalesce(fecha_hora,'')||'|'||coalesce(usuario,'')||'|'||coalesce(base,'')||'|'||coalesce(origen,'')||'|'||coalesce(archivo_origen,'')||'|'||coalesce(registros_recibidos::text,'')||'|'||coalesce(total_final::text,''))) stored unique
