-- 2) ADMINISTRACIÓN V5
create table if not exists public.app_profiles (
 user_id uuid primary key references auth.users(id) on delete cascade,
 email text not null, display_name text not null,
 role text not null default 'collaborator' check (role in ('admin','collaborator')),
 status text not null default 'pending' check (status in ('pending','active','disabled')),
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create unique index if not exists app_profiles_email_lower_uidx on public.app_profiles(lower(email));

create table if not exists public.app_permissions (
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.app_profiles(user_id) on delete cascade,
 module_key text not null,
 can_view boolean not null default false, can_create boolean not null default false,
 can_edit boolean not null default false, can_delete boolean not null default false,
 can_export boolean not null default false, updated_at timestamptz not null default now(),
 constraint app_permissions_module_check check (module_key in ('inicio','personas','vacantes','vinculaciones','explorador','ridet','administracion','usuarios','dispositivos','prioridades','auditoria','respaldos')),
 unique(user_id,module_key)
);

create table if not exists public.app_devices (
 id bigint generated by default as identity primary key,
 user_id uuid not null references public.app_profiles(user_id) on delete cascade,
 device_id text not null, hostname text, os_name text, os_version text, app_version text,
 authorized boolean not null default false, created_at timestamptz not null default now(),
 last_seen timestamptz not null default now(), unique(user_id,device_id)
);
create index if not exists idx_app_devices_user on public.app_devices(user_id);

create table if not exists public.app_audit_log (
 id bigint generated by default as identity primary key,
 user_id uuid references public.app_profiles(user_id) on delete set null,
 email text, action text not null, detail text, device_id text,
 created_at timestamptz not null default now()
);
create index if not exists idx_app_audit_created on public.app_audit_log(created_at desc);
create index if not exists idx_app_audit_user on public.app_audit_log(user_id);

create table if not exists public.app_priorities (
 id bigint generated by default as identity primary key,
 entity_type text not null, entity_id text not null, title text not null,
 description text, priority_level text not null default 'normal' check(priority_level in ('normal','alta','urgente')),
 reminder_at timestamptz, repeat_minutes integer not null default 60 check(repeat_minutes>=1),
 active boolean not null default true, created_by uuid references public.app_profiles(user_id) on delete set null,
 created_at timestamptz not null default now(), completed_at timestamptz
);

create table if not exists public.app_priority_notifications (
 priority_id bigint not null references public.app_priorities(id) on delete cascade,
 user_id uuid not null references public.app_profiles(user_id) on delete cascade,
 last_seen_at timestamptz not null default now(), primary key(priority_id,user_id)
);

-- 3) FUNCIONES DE AUTORIZACIÓN
create or replace function public.is_active_user() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.app_profiles where user_id=auth.uid() and status='active');
$$;
create or replace function public.is_admin() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.app_profiles where user_id=auth.uid() and role='admin' and status='active');
$$;
create or replace function public.has_permission(p_module text,p_action text default 'view') returns boolean language sql stable security definer set search_path=public as $$
 select public.is_admin() or exists(select 1 from public.app_permissions p join public.app_profiles u on u.user_id=p.user_id where p.user_id=auth.uid() and u.status='active' and p.module_key=p_module and case p_action when 'view' then p.can_view when 'create' then p.can_create when 'edit' then p.can_edit when 'delete' then p.can_delete when 'export' then p.can_export else false end);
$$;

