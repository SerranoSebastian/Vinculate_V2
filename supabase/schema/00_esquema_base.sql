-- 7) FUNCIÓN DE ARRANQUE DEL PRIMER ADMINISTRADOR
-- Después de crear TU usuario en Authentication, inicia sesión y ejecuta por RPC
-- bootstrap_first_admin() una sola vez, o usa el bloque manual indicado al final.
create or replace function public.bootstrap_first_admin() returns void language plpgsql security definer set search_path=public,auth as $$
declare v_email text; v_name text;
begin
 if auth.uid() is null then raise exception 'Debes estar autenticado'; end if;
 if exists(select 1 from public.app_profiles) then raise exception 'El sistema ya tiene perfiles; bootstrap cerrado'; end if;
 select lower(email),coalesce(raw_user_meta_data->>'display_name',email) into v_email,v_name from auth.users where id=auth.uid();
 insert into public.app_profiles(user_id,email,display_name,role,status) values(auth.uid(),v_email,v_name,'admin','active');
 insert into public.app_permissions(user_id,module_key,can_view,can_create,can_edit,can_delete,can_export)
 select auth.uid(),m,true,true,true,true,true from unnest(array['inicio','personas','vacantes','vinculaciones','explorador','ridet','administracion','usuarios','dispositivos','prioridades','auditoria','respaldos']) m;
end $$;
revoke all on function public.bootstrap_first_admin() from public;
grant execute on function public.bootstrap_first_admin() to authenticated;
